import fs from "node:fs";
import path from "node:path";

const projectRoot = process.cwd();
const galleryDirectory = path.join(projectRoot, "public", "images", "gallery");
const outputFile = path.join(projectRoot, "lib", "galleryPhotos.generated.ts");
const supportedExtensions = new Set([".gif", ".jpeg", ".jpg", ".png", ".svg", ".webp"]);

const photos = fs
    .readdirSync(galleryDirectory, { withFileTypes: true })
    .filter((entry) => entry.isFile())
    .filter((entry) => supportedExtensions.has(path.extname(entry.name).toLowerCase()))
    .map((entry) => entry.name)
    .sort((a, b) => a.localeCompare(b))
    .map((fileName) => `/images/gallery/${fileName}`);

const contents = `// Generated by scripts/generate-gallery-manifest.mjs. Do not edit manually.\nexport const GALLERY_PHOTOS = ${JSON.stringify(photos, null, 4)} as const;\n`;
fs.writeFileSync(outputFile, contents, "utf8");
